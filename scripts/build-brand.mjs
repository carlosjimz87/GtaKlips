// Regenerates src/brand-assets.ts from assets/brand/*. Run: node scripts/build-brand.mjs
import { readFileSync, writeFileSync } from "node:fs";
const files = {
  "icon-32.png": "image/png",
  "icon-192.png": "image/png",
  "apple-touch-icon.png": "image/png",
  "logo-96.png": "image/png",
  "og.jpg": "image/jpeg",
};
let out = "// Generated by scripts/build-brand.mjs. Do not edit.\n";
out +=
  "export const brandAssets: Record<string, { type: string; base64: string }> = {\n";
for (const [name, type] of Object.entries(files)) {
  const b64 = readFileSync(
    new URL(`../assets/brand/${name}`, import.meta.url),
  ).toString("base64");
  out += `  ${JSON.stringify(name)}: { type: ${JSON.stringify(type)}, base64: "${b64}" },\n`;
}
out += "};\n";
writeFileSync(new URL("../src/brand-assets.ts", import.meta.url), out);
